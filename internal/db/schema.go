package db

import (
	"context"
	"errors"
	"fmt"
	"regexp"
	"strings"
)

// SchemaOp is one structural change from the schema editor.
type SchemaOp struct {
	Kind   string `json:"kind"` // create_database drop_database create_table rename_table truncate_table drop_table add_column modify_column drop_column add_index drop_index add_fk drop_fk
	Schema string `json:"schema"`
	Table  string `json:"table"`
	// Name is the database for *_database, the new name for rename_table,
	// the current column name for modify_column/drop_column, the index or key name for drop_index/drop_fk.
	Name   string      `json:"name"`
	Column *Column     `json:"column,omitempty"`
	After  *string     `json:"after,omitempty"` // nil keeps the position; "" = first; otherwise after that column
	Def    *TableDef   `json:"def,omitempty"`   // create_table
	Index  *Index      `json:"index,omitempty"`
	FK     *ForeignKey `json:"fk,omitempty"`
}

var numeric = regexp.MustCompile(`^-?\d+(\.\d+)?$`)

// colDef renders one column definition.
func (c *Conn) colDef(col Column, inlinePK bool) string {
	var b strings.Builder
	b.WriteString(c.Q(col.Name))
	b.WriteString(" ")
	typ := col.Type
	if typ == "" {
		typ = "text"
	}
	switch {
	case inlinePK && c.Kind() == "sqlite":
		b.WriteString("INTEGER PRIMARY KEY AUTOINCREMENT")
		return b.String()
	case col.AutoIncrement && c.Kind() == "postgres":
		if strings.Contains(typ, "serial") {
			b.WriteString(typ)
		} else {
			b.WriteString(typ + " GENERATED BY DEFAULT AS IDENTITY")
		}
	default:
		b.WriteString(typ)
	}
	if !col.Nullable {
		b.WriteString(" NOT NULL")
	} else if c.Kind() == "mysql" {
		b.WriteString(" NULL")
	}
	if col.Default != nil && *col.Default != "" && !(col.Nullable && strings.EqualFold(*col.Default, "NULL") && c.Kind() != "mysql") {
		b.WriteString(" DEFAULT " + *col.Default)
	}
	if col.AutoIncrement && c.Kind() == "mysql" {
		b.WriteString(" AUTO_INCREMENT")
	}
	if col.Comment != "" && c.Kind() == "mysql" {
		b.WriteString(" COMMENT " + c.Literal(col.Comment))
	}
	return b.String()
}

func (c *Conn) quoteList(names []string) string {
	q := make([]string, len(names))
	for i, n := range names {
		q[i] = c.Q(n)
	}
	return strings.Join(q, ", ")
}

func (c *Conn) fkClause(fk ForeignKey, schema string) string {
	ref := c.Table(fk.RefSchema, fk.RefTable)
	if fk.RefSchema == "" && c.Kind() == "postgres" && schema != "" {
		ref = c.Table(schema, fk.RefTable)
	}
	s := fmt.Sprintf("FOREIGN KEY (%s) REFERENCES %s (%s)", c.quoteList(fk.Columns), ref, c.quoteList(fk.RefColumns))
	if fk.OnDelete != "" && !strings.EqualFold(fk.OnDelete, "NO ACTION") {
		s += " ON DELETE " + strings.ToUpper(fk.OnDelete)
	}
	if fk.OnUpdate != "" && !strings.EqualFold(fk.OnUpdate, "NO ACTION") {
		s += " ON UPDATE " + strings.ToUpper(fk.OnUpdate)
	}
	if fk.Name != "" && c.Kind() != "sqlite" {
		s = "CONSTRAINT " + c.Q(fk.Name) + " " + s
	}
	return s
}

// createTableSQL renders CREATE TABLE plus (optionally) its secondary indexes and PostgreSQL comments.
func (c *Conn) createTableSQL(def TableDef, withIndexes bool) []string {
	return c.createTable(def, withIndexes, true)
}

func (c *Conn) createTable(def TableDef, withIndexes, withFKs bool) []string {
	pk := def.PrimaryKey()
	inlinePK := ""
	if c.Kind() == "sqlite" && len(pk) == 1 {
		for _, col := range def.Columns {
			if col.Name == pk[0] && col.AutoIncrement {
				inlinePK = col.Name
			}
		}
	}
	var lines []string
	for _, col := range def.Columns {
		lines = append(lines, "  "+c.colDef(col, col.Name == inlinePK))
	}
	if len(pk) > 0 && inlinePK == "" {
		lines = append(lines, "  PRIMARY KEY ("+c.quoteList(pk)+")")
	}
	if withFKs {
		for _, fk := range def.ForeignKeys {
			lines = append(lines, "  "+c.fkClause(fk, def.Schema))
		}
	}
	out := []string{fmt.Sprintf("CREATE TABLE %s (\n%s\n);", c.Table(def.Schema, def.Name), strings.Join(lines, ",\n"))}
	if withIndexes {
		for _, ix := range def.Indexes {
			if !ix.Primary {
				out = append(out, c.createIndex(def.Schema, def.Name, ix)+";")
			}
		}
	}
	if c.Kind() == "postgres" {
		for _, col := range def.Columns {
			if col.Comment != "" {
				out = append(out, fmt.Sprintf("COMMENT ON COLUMN %s.%s IS %s;", c.Table(def.Schema, def.Name), c.Q(col.Name), c.Literal(col.Comment)))
			}
		}
	}
	return out
}

func (c *Conn) createIndex(schema, table string, ix Index) string {
	u := ""
	if ix.Unique {
		u = "UNIQUE "
	}
	return fmt.Sprintf("CREATE %sINDEX %s ON %s (%s)", u, c.Q(ix.Name), c.Table(schema, table), c.quoteList(ix.Columns))
}

// PlanSchema turns schema ops into the SQL statements that ApplySchema will run.
func (c *Conn) PlanSchema(ctx context.Context, database string, ops []SchemaOp) ([]string, error) {
	defs := map[string]*TableDef{}
	get := func(schema, table string) (*TableDef, error) {
		k := schema + "." + table
		if d, ok := defs[k]; ok {
			return d, nil
		}
		d, err := c.Describe(ctx, database, schema, table)
		if err != nil {
			return nil, err
		}
		defs[k] = &d
		return &d, nil
	}
	var out []string
	for _, op := range ops {
		stmts, err := c.planOne(op, get)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", op.Kind, err)
		}
		out = append(out, stmts...)
		if op.Kind == "rename_table" {
			if d, ok := defs[op.Schema+"."+op.Table]; ok {
				d.Name = op.Name
				defs[op.Schema+"."+op.Name] = d
				delete(defs, op.Schema+"."+op.Table)
			}
		}
		if op.Kind == "create_table" && op.Def != nil {
			d := *op.Def
			defs[op.Schema+"."+d.Name] = &d
		}
	}
	return out, nil
}

func (c *Conn) planOne(op SchemaOp, get func(schema, table string) (*TableDef, error)) ([]string, error) {
	t := c.Table(op.Schema, op.Table)
	k := c.Kind()
	switch op.Kind {
	case "create_database":
		if k == "sqlite" {
			return nil, errors.New("SQLite has one database per file")
		}
		if k == "mysql" {
			return []string{"CREATE DATABASE " + c.Q(op.Name) + " CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;"}, nil
		}
		return []string{"CREATE DATABASE " + c.Q(op.Name) + ";"}, nil
	case "drop_database":
		if k == "sqlite" {
			return nil, errors.New("delete the SQLite file instead")
		}
		return []string{"DROP DATABASE " + c.Q(op.Name) + ";"}, nil
	case "create_table":
		if op.Def == nil || op.Def.Name == "" || len(op.Def.Columns) == 0 {
			return nil, errors.New("a new table needs a name and at least one column")
		}
		d := *op.Def
		d.Schema = op.Schema
		return c.createTableSQL(d, true), nil
	case "rename_table":
		if k == "mysql" {
			return []string{fmt.Sprintf("RENAME TABLE %s TO %s;", t, c.Q(op.Name))}, nil
		}
		return []string{fmt.Sprintf("ALTER TABLE %s RENAME TO %s;", t, c.Q(op.Name))}, nil
	case "truncate_table":
		if k == "sqlite" {
			return []string{"DELETE FROM " + t + ";"}, nil
		}
		return []string{"TRUNCATE TABLE " + t + ";"}, nil
	case "drop_table":
		d, err := get(op.Schema, op.Table)
		if err == nil && d.IsView {
			return []string{"DROP VIEW " + t + ";"}, nil
		}
		return []string{"DROP TABLE " + t + ";"}, nil
	}

	d, err := get(op.Schema, op.Table)
	if err != nil {
		return nil, err
	}
	switch op.Kind {
	case "add_column":
		if op.Column == nil || op.Column.Name == "" {
			return nil, errors.New("column name is required")
		}
		col := *op.Column
		var stmts []string
		switch {
		case k == "mysql":
			stmts = []string{fmt.Sprintf("ALTER TABLE %s ADD COLUMN %s%s;", t, c.colDef(col, false), c.position(op.After))}
		case k == "postgres":
			if op.After != nil {
				return nil, errors.New("PostgreSQL always adds columns at the end")
			}
			stmts = []string{fmt.Sprintf("ALTER TABLE %s ADD COLUMN %s;", t, c.colDef(col, false))}
			if col.Comment != "" {
				stmts = append(stmts, fmt.Sprintf("COMMENT ON COLUMN %s.%s IS %s;", t, c.Q(col.Name), c.Literal(col.Comment)))
			}
		case op.After == nil:
			stmts = []string{fmt.Sprintf("ALTER TABLE %s ADD COLUMN %s;", t, c.colDef(col, false))}
		}
		next := *d
		next.Columns = insertColumn(d.Columns, col, op.After)
		if stmts == nil {
			stmts = c.rebuild(*d, next, map[string]string{})
		}
		*d = next
		return stmts, nil
	case "modify_column":
		if op.Column == nil {
			return nil, errors.New("column is required")
		}
		old, i := findColumn(d.Columns, op.Name)
		if i < 0 {
			return nil, fmt.Errorf("column %s not found", op.Name)
		}
		col := *op.Column
		next := *d
		next.Columns = append([]Column{}, d.Columns...)
		next.Columns[i] = col
		if op.After != nil {
			next.Columns = insertColumn(append(next.Columns[:i:i], next.Columns[i+1:]...), col, op.After)
		}
		next.Indexes = renameInIndexes(d.Indexes, op.Name, col.Name)
		next.ForeignKeys = renameInFKs(d.ForeignKeys, op.Name, col.Name)
		var stmts []string
		switch k {
		case "mysql":
			stmts = []string{fmt.Sprintf("ALTER TABLE %s CHANGE COLUMN %s %s%s;", t, c.Q(op.Name), c.colDef(col, false), c.position(op.After))}
		case "postgres":
			if op.After != nil {
				return nil, errors.New("PostgreSQL cannot reorder columns")
			}
			stmts = c.pgAlterColumn(t, old, col)
		default:
			stmts = c.rebuild(*d, next, map[string]string{col.Name: op.Name})
		}
		*d = next
		return stmts, nil
	case "drop_column":
		_, i := findColumn(d.Columns, op.Name)
		if i < 0 {
			return nil, fmt.Errorf("column %s not found", op.Name)
		}
		next := *d
		next.Columns = append(append([]Column{}, d.Columns[:i]...), d.Columns[i+1:]...)
		next.Indexes = dropFromIndexes(d.Indexes, op.Name)
		next.ForeignKeys = dropFromFKs(d.ForeignKeys, op.Name)
		var stmts []string
		if k == "sqlite" {
			stmts = c.rebuild(*d, next, map[string]string{})
		} else {
			stmts = []string{fmt.Sprintf("ALTER TABLE %s DROP COLUMN %s;", t, c.Q(op.Name))}
		}
		*d = next
		return stmts, nil
	case "add_index":
		if op.Index == nil || len(op.Index.Columns) == 0 {
			return nil, errors.New("an index needs at least one column")
		}
		ix := *op.Index
		var stmts []string
		if ix.Primary {
			if k == "sqlite" {
				next := *d
				next.Indexes = append([]Index{ix}, withoutPrimary(d.Indexes)...)
				stmts = c.rebuild(*d, next, map[string]string{})
				*d = next
				return stmts, nil
			}
			stmts = []string{fmt.Sprintf("ALTER TABLE %s ADD PRIMARY KEY (%s);", t, c.quoteList(ix.Columns))}
		} else {
			if ix.Name == "" {
				ix.Name = op.Table + "_" + strings.Join(ix.Columns, "_") + map[bool]string{true: "_unique", false: "_index"}[ix.Unique]
			}
			stmts = []string{c.createIndex(op.Schema, op.Table, ix) + ";"}
		}
		d.Indexes = append(d.Indexes, ix)
		return stmts, nil
	case "drop_index":
		var ix *Index
		for i := range d.Indexes {
			if d.Indexes[i].Name == op.Name {
				ix = &d.Indexes[i]
			}
		}
		if ix == nil {
			return nil, fmt.Errorf("index %s not found", op.Name)
		}
		var stmts []string
		switch {
		case ix.Primary && k == "mysql":
			stmts = []string{fmt.Sprintf("ALTER TABLE %s DROP PRIMARY KEY;", t)}
		case ix.Primary && k == "postgres":
			stmts = []string{fmt.Sprintf("ALTER TABLE %s DROP CONSTRAINT %s;", t, c.Q(ix.Name))}
		case ix.Primary, k == "sqlite" && strings.HasPrefix(ix.Name, "sqlite_autoindex"):
			next := *d
			next.Indexes = nil
			for _, x := range d.Indexes {
				if x.Name != ix.Name {
					next.Indexes = append(next.Indexes, x)
				}
			}
			if ix.Primary {
				next.Columns = append([]Column{}, d.Columns...)
				for i := range next.Columns {
					next.Columns[i].AutoIncrement = false
				}
			}
			stmts = c.rebuild(*d, next, map[string]string{})
		case k == "mysql":
			stmts = []string{fmt.Sprintf("DROP INDEX %s ON %s;", c.Q(ix.Name), t)}
		case k == "postgres" && ix.Unique:
			// unique constraints own their index
			stmts = []string{fmt.Sprintf("ALTER TABLE %s DROP CONSTRAINT IF EXISTS %s;", t, c.Q(ix.Name)), fmt.Sprintf("DROP INDEX IF EXISTS %s;", c.Table(op.Schema, ix.Name))}
		case k == "postgres":
			stmts = []string{"DROP INDEX " + c.Table(op.Schema, ix.Name) + ";"}
		default:
			stmts = []string{"DROP INDEX " + c.Q(ix.Name) + ";"}
		}
		var keep []Index
		for _, x := range d.Indexes {
			if x.Name != op.Name {
				keep = append(keep, x)
			}
		}
		d.Indexes = keep
		return stmts, nil
	case "add_fk":
		if op.FK == nil || len(op.FK.Columns) == 0 || len(op.FK.Columns) != len(op.FK.RefColumns) || op.FK.RefTable == "" {
			return nil, errors.New("a foreign key needs columns, a referenced table and as many referenced columns")
		}
		fk := *op.FK
		if fk.Name == "" && k != "sqlite" {
			fk.Name = op.Table + "_" + strings.Join(fk.Columns, "_") + "_foreign"
		}
		next := *d
		next.ForeignKeys = append(append([]ForeignKey{}, d.ForeignKeys...), fk)
		var stmts []string
		if k == "sqlite" {
			stmts = c.rebuild(*d, next, map[string]string{})
		} else {
			stmts = []string{fmt.Sprintf("ALTER TABLE %s ADD %s;", t, c.fkClause(fk, op.Schema))}
		}
		*d = next
		return stmts, nil
	case "drop_fk":
		next := *d
		next.ForeignKeys = nil
		found := false
		for _, fk := range d.ForeignKeys {
			if fk.Name == op.Name {
				found = true
				continue
			}
			next.ForeignKeys = append(next.ForeignKeys, fk)
		}
		if !found {
			return nil, fmt.Errorf("foreign key %s not found", op.Name)
		}
		var stmts []string
		switch k {
		case "mysql":
			stmts = []string{fmt.Sprintf("ALTER TABLE %s DROP FOREIGN KEY %s;", t, c.Q(op.Name))}
		case "postgres":
			stmts = []string{fmt.Sprintf("ALTER TABLE %s DROP CONSTRAINT %s;", t, c.Q(op.Name))}
		default:
			stmts = c.rebuild(*d, next, map[string]string{})
		}
		*d = next
		return stmts, nil
	}
	return nil, fmt.Errorf("unknown operation %q", op.Kind)
}

func (c *Conn) position(after *string) string {
	if after == nil {
		return ""
	}
	if *after == "" {
		return " FIRST"
	}
	return " AFTER " + c.Q(*after)
}

func (c *Conn) pgAlterColumn(t string, old, col Column) []string {
	var out []string
	name := c.Q(old.Name)
	if col.Name != old.Name {
		out = append(out, fmt.Sprintf("ALTER TABLE %s RENAME COLUMN %s TO %s;", t, name, c.Q(col.Name)))
		name = c.Q(col.Name)
	}
	if col.Type != old.Type {
		out = append(out, fmt.Sprintf("ALTER TABLE %s ALTER COLUMN %s TYPE %s USING %s::%s;", t, name, col.Type, name, col.Type))
	}
	if col.Nullable != old.Nullable {
		if col.Nullable {
			out = append(out, fmt.Sprintf("ALTER TABLE %s ALTER COLUMN %s DROP NOT NULL;", t, name))
		} else {
			out = append(out, fmt.Sprintf("ALTER TABLE %s ALTER COLUMN %s SET NOT NULL;", t, name))
		}
	}
	od, nd := deref(old.Default), deref(col.Default)
	if od != nd {
		if nd == "" {
			out = append(out, fmt.Sprintf("ALTER TABLE %s ALTER COLUMN %s DROP DEFAULT;", t, name))
		} else {
			out = append(out, fmt.Sprintf("ALTER TABLE %s ALTER COLUMN %s SET DEFAULT %s;", t, name, nd))
		}
	}
	if col.AutoIncrement != old.AutoIncrement {
		if col.AutoIncrement {
			out = append(out, fmt.Sprintf("ALTER TABLE %s ALTER COLUMN %s ADD GENERATED BY DEFAULT AS IDENTITY;", t, name))
		} else {
			out = append(out, fmt.Sprintf("ALTER TABLE %s ALTER COLUMN %s DROP IDENTITY IF EXISTS;", t, name))
		}
	}
	if col.Comment != old.Comment {
		out = append(out, fmt.Sprintf("COMMENT ON COLUMN %s.%s IS %s;", t, name, c.Literal(col.Comment)))
	}
	return out
}

func deref(s *string) string {
	if s == nil {
		return ""
	}
	return *s
}

// rebuild recreates a SQLite table with a new definition, copying the data.
// renamed maps new column names to their old names.
func (c *Conn) rebuild(old, next TableDef, renamed map[string]string) []string {
	tmp := "_dbro_new_" + next.Name
	tmpDef := next
	tmpDef.Name = tmp
	stmts := []string{"PRAGMA foreign_keys = OFF;", "BEGIN;"}
	stmts = append(stmts, c.createTable(tmpDef, false, true)...)
	var to, from []string
	for _, col := range next.Columns {
		src := col.Name
		if r, ok := renamed[col.Name]; ok {
			src = r
		}
		if _, i := findColumn(old.Columns, src); i >= 0 {
			to = append(to, c.Q(col.Name))
			from = append(from, c.Q(src))
		}
	}
	if len(to) > 0 {
		stmts = append(stmts, fmt.Sprintf("INSERT INTO %s (%s) SELECT %s FROM %s;", c.Q(tmp), strings.Join(to, ", "), strings.Join(from, ", "), c.Q(old.Name)))
	}
	stmts = append(stmts, "DROP TABLE "+c.Q(old.Name)+";", fmt.Sprintf("ALTER TABLE %s RENAME TO %s;", c.Q(tmp), c.Q(next.Name)))
	for _, ix := range next.Indexes {
		if ix.Primary {
			continue
		}
		if strings.HasPrefix(ix.Name, "sqlite_autoindex") {
			// inline UNIQUE constraints come back as named unique indexes
			ix.Name = next.Name + "_" + strings.Join(ix.Columns, "_") + "_unique"
		}
		stmts = append(stmts, c.createIndex("", next.Name, ix)+";")
	}
	return append(stmts, "COMMIT;", "PRAGMA foreign_keys = ON;")
}

func findColumn(cols []Column, name string) (Column, int) {
	for i, c := range cols {
		if c.Name == name {
			return c, i
		}
	}
	return Column{}, -1
}

func insertColumn(cols []Column, col Column, after *string) []Column {
	out := append([]Column{}, cols...)
	if after == nil {
		return append(out, col)
	}
	pos := 0
	if *after != "" {
		_, i := findColumn(out, *after)
		pos = i + 1
	}
	out = append(out, Column{})
	copy(out[pos+1:], out[pos:])
	out[pos] = col
	return out
}

func renameInIndexes(ixs []Index, from, to string) []Index {
	out := make([]Index, len(ixs))
	for i, ix := range ixs {
		ix.Columns = replaceAll(ix.Columns, from, to)
		out[i] = ix
	}
	return out
}

func renameInFKs(fks []ForeignKey, from, to string) []ForeignKey {
	out := make([]ForeignKey, len(fks))
	for i, fk := range fks {
		fk.Columns = replaceAll(fk.Columns, from, to)
		out[i] = fk
	}
	return out
}

func replaceAll(xs []string, from, to string) []string {
	out := append([]string{}, xs...)
	for i := range out {
		if out[i] == from {
			out[i] = to
		}
	}
	return out
}

func dropFromIndexes(ixs []Index, col string) []Index {
	var out []Index
	for _, ix := range ixs {
		var cols []string
		for _, c := range ix.Columns {
			if c != col {
				cols = append(cols, c)
			}
		}
		if len(cols) > 0 {
			ix.Columns = cols
			out = append(out, ix)
		}
	}
	return out
}

func dropFromFKs(fks []ForeignKey, col string) []ForeignKey {
	var out []ForeignKey
	for _, fk := range fks {
		uses := false
		for _, c := range fk.Columns {
			uses = uses || c == col
		}
		if !uses {
			out = append(out, fk)
		}
	}
	return out
}

func withoutPrimary(ixs []Index) []Index {
	var out []Index
	for _, ix := range ixs {
		if !ix.Primary {
			out = append(out, ix)
		}
	}
	return out
}

// ApplySchema runs planned statements in order on one connection.
// Statements from a SQLite rebuild are rolled back together when one fails.
func (c *Conn) ApplySchema(ctx context.Context, database string, stmts []string) error {
	p, err := c.pool(database)
	if err != nil {
		return err
	}
	conn, err := p.Conn(ctx)
	if err != nil {
		return err
	}
	defer conn.Close()
	inTx := false
	for _, s := range stmts {
		if _, err := c.run(ctx, conn, database, strings.TrimSuffix(s, ";"), 0); err != nil {
			if inTx {
				conn.ExecContext(context.Background(), "ROLLBACK")
				if c.Kind() == "sqlite" {
					conn.ExecContext(context.Background(), "PRAGMA foreign_keys = ON")
				}
			}
			return fmt.Errorf("%s\n%w", s, err)
		}
		switch strings.ToUpper(strings.TrimSuffix(s, ";")) {
		case "BEGIN":
			inTx = true
		case "COMMIT":
			inTx = false
		}
	}
	return nil
}
